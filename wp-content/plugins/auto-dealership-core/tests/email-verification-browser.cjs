const fs = require('fs');
const path = require('path');
const config = JSON.parse(fs.readFileSync(0, 'utf8'));
const { chromium } = require(path.join(config.root, '.tmp/accessibility-tools/node_modules/playwright-core'));
let phase = 'startup';
let browser;
let passed = 0;
const check = (ok, label) => { if (!ok) throw new Error(label); passed++; process.stdout.write(`PASS Browser: ${label}\n`); };
const link = (purpose, token, lang = 'en') => `${config.base}?adc_verify=1&purpose=${purpose}&lang=${lang}#token=${token}`;
const state = async (context, token) => (await context.request.get(`${config.base}?adc_test_state=${token.split('.')[0]}`)).json();
(async () => {
  browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true});
  const context = await browser.newContext();
  const page = await context.newPage();
  page.setDefaultTimeout(15000);page.setDefaultNavigationTimeout(30000);
  const scriptErrors = [];
  page.on('pageerror', () => scriptErrors.push(true));
  phase = 'account link';
  const scan = await context.request.get(link('account', config.account));
  check((await state(context, config.account)).status === 'pending', 'HTTP GET without browser script does not activate accounts');
  check(scan.headers()['referrer-policy'] === 'no-referrer' && scan.headers()['content-security-policy'].includes("default-src 'none'") && scan.headers()['cache-control'].includes('no-store'), 'page applies restrictive CSP, referrer policy and cache controls');
  await page.goto(link('account', config.account));
  await page.waitForURL(url => url.searchParams.get('cd_account') === 'login');
  await page.locator('.adc-activation-notice').waitFor();
  check(!new URL(page.url()).hash, 'proof removed from browser address after capture');
  check((await page.locator('.adc-activation-notice').innerText()).includes('Your account is confirmed'), 'activation needs no password and redirects to sign-in with confirmation');
  check((await state(context, config.account)).status === 'active', 'opening the account link activates automatically');
  check(!(await context.cookies()).some(cookie => cookie.name.startsWith('wordpress_logged_in_')), 'confirmation never creates a login cookie');
  check(await page.locator('.cd-auth-form form:not([hidden]) input[type=password]').count() === 1, 'normal login form is shown only after successful activation');
  await page.reload();check(await page.locator('.adc-activation-notice').count() === 0, 'success notice is consumed once');
  phase = 'account replay';
  await page.goto('about:blank');
  await page.goto(link('account', config.account));
  await page.waitForURL(url => url.searchParams.get('cd_account') === 'login');
  await page.locator('.adc-activation-notice').waitFor();
  check((await page.locator('.adc-activation-notice').innerText()).includes('already active'), 'a valid consumed account proof reports activation without repeating it');
  phase = 'newsletter confirmation';
  await page.setViewportSize({width:375,height:812});
  await page.goto(link('newsletter', config.newsletter));
  check(await page.locator('#adc-verify-password').count() === 0 && (await state(context, config.newsletter)).status === 'pending', 'newsletter GET keeps consent pending without asking for an account password');
  const rejectedPost = await context.request.post(`${config.base}?adc_verify=1&purpose=newsletter&lang=en`, {form:{operation:'confirm',token:config.newsletter}});
  check(rejectedPost.status() === 403 && (await state(context, config.newsletter)).status === 'pending', 'POST without a valid form nonce cannot activate a subscription');
  const purposeNonce = await page.locator('#adc-confirm-nonce').inputValue();
  const wrongPurpose = await context.request.post(`${config.base}?adc_verify=1&purpose=account&lang=en`, {form:{operation:'confirm',token:config.newsletter,password:config.password,_wpnonce:purposeNonce}});
  check(wrongPurpose.status() === 400 && (await state(context, config.newsletter)).status === 'pending', 'changing the page purpose cannot repurpose a newsletter proof');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'verification page fits a mobile viewport');
  await page.screenshot({path:path.join(config.root, '.tmp/email-verification-mobile.png'),fullPage:true});
  await Promise.all([page.waitForNavigation(), page.locator('#adc-verify-submit').click()]);
  check((await page.locator('h1').innerText()).includes('confirmed') && (await state(context, config.newsletter)).status === 'active', 'newsletter becomes active after explicit POST');
  phase = 'concurrent newsletter confirmation';
  const first = await context.newPage(); const second = await context.newPage();
  await Promise.all([first.goto(link('newsletter', config.concurrent,'ar')), second.goto(link('newsletter', config.concurrent,'ar'))]);
  await Promise.all([first.waitForNavigation().then(() => {}), second.waitForNavigation().then(() => {}), first.locator('#adc-verify-submit').click(), second.locator('#adc-verify-submit').click()]);
  const successes = await first.locator('p[role=status]:visible:not(#adc-resend-wait):not(#adc-confirm-help)').count() + await second.locator('p[role=status]:visible:not(#adc-resend-wait):not(#adc-confirm-help)').count();
  const failures = await first.locator('[role=alert]:visible').count() + await second.locator('[role=alert]:visible').count();
  check(successes === 1 && failures === 1 && (await state(context,config.concurrent)).used, 'simultaneous POSTs consume the challenge exactly once');
  phase = 'public resend';
  await page.goto(`${config.base}?adc_verify=1&purpose=newsletter&lang=en`);
  check(await page.locator('#adc-verify-form').isHidden(), 'page without an email proof shows resend guidance instead of an unusable confirmation form');
  await page.locator('#adc-resend-email').fill('unknown@example.invalid');
  await page.waitForFunction(() => !document.querySelector('[data-resend-button]').disabled, null, { timeout: 65000 });
  await Promise.all([page.waitForNavigation(), page.locator('button').last().click()]);
  const unknownMessage = await page.locator('p[role=status]:not(#adc-resend-wait):not(#adc-confirm-help)').innerText();
  await page.locator('#adc-resend-email').fill('browser-newsletter@example.invalid');
  check(await page.locator('[data-resend-button]').isDisabled(), 'resend cooldown disables repeated browser submissions');
  await page.waitForFunction(() => !document.querySelector('[data-resend-button]').disabled, null, { timeout: 65000 });
  await Promise.all([page.waitForNavigation(), page.locator('button').last().click()]);
  check((await page.locator('p[role=status]:not(#adc-resend-wait):not(#adc-confirm-help)').innerText()) === unknownMessage, 'resend response does not reveal an unknown versus active address');
  check(scriptErrors.length === 0, 'verification pages have no JavaScript errors');
  phase = 'verification rate limit';
  const formNonce = await page.locator('#adc-confirm-nonce').inputValue();
  let limited;
  for (let attempt=0;attempt<25;attempt++) {
    const reply = await context.request.post(`${config.base}?adc_verify=1&purpose=newsletter&lang=en`, {form:{operation:'confirm',token:config.newsletter,_wpnonce:formNonce}});
    if(reply.status() === 429) {limited=reply; break;}
  }
  check(limited && Number(limited.headers()['retry-after']) > 0, 'excessive confirmation attempts receive a bounded Retry-After response');
  process.stdout.write(`Browser verification passed (${passed} checks).\n`);
  await browser.close();
})().catch(async (error) => { process.stderr.write(`Browser verification failed during ${phase}. ${error.name}: ${String(error.message).split('\n')[0].replace(/token=[^\s&#]+/g,'token=[redacted]')}\n`); if (browser) {for(const context of browser.contexts())for(const page of context.pages()){process.stderr.write('Verification page heading: '+await page.locator('body').innerText().then(t=>t.slice(0,350)).catch(()=>'(unavailable)')+'\n');}await browser.close();} process.exitCode=1; });
